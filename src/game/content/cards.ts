function withEconomy(
  id: string,
  kind: "gear" | "attack" | "defense",
): NonNullable<CardDefinition["economy"]> {
  const { value, chiCost, restrictions, slotType } = CARD_ECONOMY[id];
  return { kind, value, chiCost, restrictions, slotType };
}

